namespace OSRSIdle;

public class InventoryItem
{
    // ============================================================
    // ITEM
    // ============================================================

    public Item Item { get; set; }


    // ============================================================
    // QUANTITY
    // ============================================================

    public int Quantity { get; set; }


    // ============================================================
    // CONSTRUCTOR
    // ============================================================

    public InventoryItem(
        Item item,
        int quantity = 1)
    {
        Item = item;
        Quantity = quantity;
    }
}