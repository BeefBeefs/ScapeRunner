    private static void AddEquipmentDrop(
        string enemyName,
        Item item,
        double chance,
        DropRarity rarity)
    {
        Enemy enemy = EnemyRegistry.Single(enemy => enemy.Name == enemyName);

        enemy.DropTable.Drops.Add(new Drop
        {
            Item = item,
            Chance = chance,
            MinQuantity = 1,
            MaxQuantity = 1,
            Rarity = rarity
        });
    }
